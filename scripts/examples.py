"""Regenerate docs/examples.md: `make examples`.

Runs the real pipeline in offline mode (no API keys), so the output is
deterministic and anyone can reproduce it. With keys set, the live app adds the
LLM composer, but every plan still passes the same safety filter and validator.
"""

from __future__ import annotations

import os
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

for k in ("ANTHROPIC_API_KEY", "OPENAI_API_KEY"):
    os.environ.pop(k, None)
os.environ["FC_EVENTS_PATH"] = os.path.join(tempfile.mkdtemp(), "events.jsonl")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.plan.generate import generate

EXAMPLES = [
    (
        "Injury: knee",
        "jordan",
        "Lower-body exercises that avoid aggravating a knee injury",
    ),
    (
        "Limited equipment",
        "priya",
        "No barbell today, only dumbbells and a kettlebell. Upper body.",
    ),
    (
        "Exercise-family exclusion",
        "jordan",
        "Full body, no deadlift variations, 40 min",
    ),
    (
        "Fail-closed: a concern the graph can't place",
        "jordan",
        "Something's off with her hammy, sore since Saturday. Lower body.",
    ),
]
SHOWN_PER_RULE = 4


def dose(i: dict) -> str:
    work = f"{i['duration_s']} s" if i["duration_s"] else f"{i['reps']} reps"
    return f"{i['sets']} × {work}" + (" each side" if i["each_side"] else "")


def section(title: str, member: str, prompt: str) -> list[str]:
    r = generate(member, prompt)
    out = [
        f"## {title}",
        "",
        f"- **Member:** {member.capitalize()}",
        f"- **Coach request:** “{prompt}”",
        "",
    ]
    if r["status"] != "ok":
        out += ["**Result:** no plan. The system asks the coach first:", ""]
        out += [f"> {q}" for q in r.get("questions", [])] + [""]
        return out
    res = r["resolution"]
    out += ["**How the request was read** (resolver → graph concepts):", ""]
    out += [
        f"- “{m['text']}” → `{m['concept']}` ({m['type']}, {m['role']}, {m['pass']} match)"
        for m in res["mentions"]
    ]
    out += [f"- note: {n}" for n in res["notes"]] + [""]
    p = r["plan"]
    out += [
        f"**Plan** ({p['est_min']:.0f} of {p['budget_min']} min, RPE cap {r['readiness']['rpe_cap']}):",
        "",
    ]
    out += [
        "| Block | Exercise | Dose | Rest | RPE | Why |",
        "|---|---|---|---|---|---|",
    ]
    out += [
        f"| {i['block']} | {i['name']} | {dose(i)} | {i['rest_s']} s | {i['rpe_target'] or '-'} | {'; '.join(i['why']) or '-'} |"
        for i in p["items"]
    ]
    acts = {a["id"]: a for a in r["provenance"]["activities"]}
    by_rule: dict[str, list[dict]] = defaultdict(list)
    for e in acts["safety_filter"]["generated_excluded"]:
        by_rule[e["reason"]["rule"]].append(e)
    out += [
        "",
        "**Filtering trace** (every exclusion is a graph path, not a model judgment):",
        "",
    ]
    for rule, items in sorted(
        by_rule.items(), key=lambda kv: kv[0].startswith("equipment")
    ):
        src = items[0]["reason"]["source"]
        out.append(
            f"- **{rule}**: {len(items)} excluded"
            + (f" (source: {src})" if src else "")
        )
        for e in items[:SHOWN_PER_RULE]:
            out.append(
                f"  - {e['exercise']}: {e['reason']['text']}\n    - path: `{' → '.join(e['reason']['path'])}`"
            )
        if len(items) > SHOWN_PER_RULE:
            out.append(f"  - … and {len(items) - SHOWN_PER_RULE} more")
    repairs = acts["validate"]["repairs"]
    out += [
        "",
        f"**Validator:** {'; '.join(repairs) if repairs else 'no repairs needed'}",
        "",
    ]
    out += (
        ["**Provenance summary:**", ""]
        + [f"- {s}" for s in r["provenance"]["summary"]]
        + [""]
    )
    return out


def main() -> None:
    lines = [
        "# Example inputs and plans",
        "",
        "Generated by `make examples` (offline mode: rules extractor + deterministic builder, so the output is reproducible).",
        "On the live site the LLM composer picks from the same safe set, and the same validator checks its output.",
        "",
    ]
    for ex in EXAMPLES:
        lines += section(*ex)
    (ROOT / "docs" / "examples.md").write_text("\n".join(lines).rstrip() + "\n")


if __name__ == "__main__":
    main()
